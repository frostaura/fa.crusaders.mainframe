"""Generates this directory's cases.json and manifest.json: the signed-OTA contract.

Run it as `python3 src/contracts/device-protocol/ota/gen_cases.py` from anywhere in
the repository. Standard library only, on purpose: this file is the REFERENCE
implementation of the release manifest, the RSA-2048 PKCS#1 v1.5 signature over it
and the offer grammar, and none of the three implementations that read the output
(the shared firmware library `devota`, the ESP8266 and ESP32 images through it, and
the server) may be checked against itself. A regeneration is byte-identical.

THE KEYS BELOW ARE TEST KEYS. They exist so the corpus can carry signatures that
verify. They sign nothing that is ever offered to a board: the production key pair
is generated by the founder (`src/iot/tools/ota_sign.py keygen`), its private half
never enters this repository, and its public modulus is compiled into each image from
`secrets.h` and configured on the server as `DeviceOta:PublicKeyModulus`. A board
built with the test modulus must not exist outside a test binary — the firmware's
secrets guards refuse it (docs/specs/device-api.md §7).

Contract: docs/specs/device-api.md §7 (OTA). Families: src/contracts/device-protocol/README.md.
"""
