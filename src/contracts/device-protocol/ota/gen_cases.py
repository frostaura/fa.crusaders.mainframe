# --- Contract constants -----------------------------------------------------------

MANIFEST_MAGIC = "crusaders-ota/1"
PATH_PREFIX = "/api/v1/device/firmware/"
# The largest image each target's flash layout can stage. court_bridge: the
# eagle.flash.4m2m sketch region as PlatformIO reports it; door_gate: one 1.25 MB
# app slot of the default esp32 partition table. A board still checks its own free
# staging space; this is the bound the server refuses an upload against.
TARGET_MAX_BYTES = {"court_bridge": 1044464, "door_gate": 1310720}
SIG_BYTES = 256
SIG_B64_LEN = 342  # 256 bytes, base64url, unpadded

VERSION_RE = re.compile(r"^(0|[1-9][0-9]{0,2})\.(0|[1-9][0-9]{0,2})\.(0|[1-9][0-9]{0,2})$")
PATH_RE = re.compile(r"^/api/v1/device/firmware/[A-Za-z0-9_-]{1,64}$")
SHA_RE = re.compile(r"^[0-9a-f]{64}$")
B64URL_RE = re.compile(r"^[A-Za-z0-9_-]+$")

# SHA-256 DigestInfo prefix (RFC 8017 §9.2 note 1).
DIGEST_INFO_SHA256 = bytes.fromhex("3031300d060960864801650304020105000420")


def manifest_text(target: str, version: str, size: int, sha256: str) -> str:
    """The exact bytes that are signed. Five LF-terminated lines, no trailing space,
    lowercase hex. Binding the target and the version into the signed text is what
    stops a signed image for one board, or an older signed image, being offered as
    something it is not."""
    return f"{MANIFEST_MAGIC}\n{target}\n{version}\n{size}\n{sha256}\n"


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode("ascii").rstrip("=")


def b64url_decode(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def encoded_message(digest: bytes) -> bytes:
    t = DIGEST_INFO_SHA256 + digest
    ps = b"\xff" * (SIG_BYTES - len(t) - 3)
    return b"\x00\x01" + ps + b"\x00" + t


def sign(text: str, n: int = N, d: int = D) -> str:
    digest = hashlib.sha256(text.encode("ascii")).digest()
    m = int.from_bytes(encoded_message(digest), "big")
    return b64url(pow(m, d, n).to_bytes(SIG_BYTES, "big"))


def verify(text: str, sig: str, n: int = N) -> tuple:
    """(valid, reason). Strict: the decoded block must EQUAL the expected encoding —
    no ASN.1 parsing, which is where PKCS#1 v1.5 verifiers have historically broken."""
    if len(sig) != SIG_B64_LEN or not B64URL_RE.match(sig):
        return False, "sig_encoding"
    raw = b64url_decode(sig)
    if len(raw) != SIG_BYTES:
        return False, "sig_encoding"
    s = int.from_bytes(raw, "big")
    if s >= n:
        return False, "sig_range"
    digest = hashlib.sha256(text.encode("ascii")).digest()
    if pow(s, E, n).to_bytes(SIG_BYTES, "big") != encoded_message(digest):
        return False, "sig"
    return True, "ok"


def version_tuple(v: str):
    m = VERSION_RE.match(v)
    return tuple(int(x) for x in m.groups()) if m else None


def accept_version(running: str, offered: str, failed: list) -> tuple:
    """Strictly newer, never a version this board rolled back from. A downgrade is
    published as a HIGHER version carrying the older code — so a replayed old image
    can never be offered past this check."""
    r, o = version_tuple(running), version_tuple(offered)
    if o is None:
        return False, "version_format"
    if r is None:
        return False, "running_unknown"
    if offered in failed:
        return False, "failed_before"
    if o <= r:
        return False, "not_newer"
    return True, "ok"


def parse_offer(ota: dict, own_target: str) -> tuple:
    """The heartbeat's `ota` object, checked in this order; the first failing rule is
    the reason. Every field is mandatory; an extra field is ignored (additive)."""
    for key in ("target", "version", "size", "sha256", "sig", "path"):
        if key not in ota:
            return False, "missing_" + key
    if not isinstance(ota["target"], str) or ota["target"] not in TARGET_MAX_BYTES:
        return False, "target_unknown"
    if ota["target"] != own_target:
        return False, "target_mismatch"
    if not isinstance(ota["version"], str) or version_tuple(ota["version"]) is None:
        return False, "version_format"
    size = ota["size"]
    if not isinstance(size, int) or isinstance(size, bool) or size < 1 or size > TARGET_MAX_BYTES[own_target]:
        return False, "size"
    if not isinstance(ota["sha256"], str) or not SHA_RE.match(ota["sha256"]):
        return False, "sha256_format"
    if not isinstance(ota["sig"], str) or len(ota["sig"]) != SIG_B64_LEN or not B64URL_RE.match(ota["sig"]):
        return False, "sig_encoding"
    if not isinstance(ota["path"], str) or not PATH_RE.match(ota["path"]):
        return False, "path"
    return True, "ok"


def test_image(n: int) -> bytes:
    """Deterministic bytes standing in for a firmware image: an ESP image magic byte
    first, then an LCG stream, so a regeneration is a no-op diff."""
    out = bytearray(b"\xe9")
    state = 0x5DEECE66D
    while len(out) < n:
        state = (state * 6364136223846793005 + 1442695040888963407) & ((1 << 64) - 1)
        out.append((state >> 56) & 0xFF)
    return bytes(out)


def compact(obj) -> str:
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=False)


def main() -> int:
    image = test_image(1536)
    image_sha = hashlib.sha256(image).hexdigest()
    target, version = "court_bridge", "3.0.1"
    text = manifest_text(target, version, len(image), image_sha)
    sig = sign(text)
    path = PATH_PREFIX + "r1b2c3d4"
    offer = {"target": target, "version": version, "size": len(image),
             "sha256": image_sha, "sig": sig, "path": path}

    gate_image = test_image(2048)[::-1]
    gate_sha = hashlib.sha256(gate_image).hexdigest()
    gate_text = manifest_text("door_gate", "2.0.1", len(gate_image), gate_sha)
    gate_offer = {"target": "door_gate", "version": "2.0.1", "size": len(gate_image),
                  "sha256": gate_sha, "sig": sign(gate_text), "path": PATH_PREFIX + "g9f8e7d6"}

    cases = {
        "description": (
            "Signed OTA for the two ESP chips (court_bridge, door_gate): the canonical release manifest, "
            "the RSA-2048 PKCS#1 v1.5 SHA-256 signature over it, the version gate, the heartbeat `ota` offer "
            "grammar, and one small image a board streams and hashes. Generated by gen_cases.py beside this "
            "file with TEST keys only. Contract: docs/specs/device-api.md section 7."),
        "public_key": {"n_hex": format(N, "x"), "e": E},
        "other_public_key": {"n_hex": format(N_OTHER, "x"), "e": E},
        "constants": {"manifest_magic": MANIFEST_MAGIC, "path_prefix": PATH_PREFIX,
                      "target_max_bytes": TARGET_MAX_BYTES, "sig_b64_len": SIG_B64_LEN},
        "manifests": [],
        "signatures": [],
        "versions": [],
        "offers": [],
        "images": [],
    }

    def manifest_case(cid, note, t, v, size, sha):
        txt = manifest_text(t, v, size, sha)
        cases["manifests"].append({
            "id": cid, "note": note,
            "fields": {"target": t, "version": v, "size": size, "sha256": sha},
            "text_hex": txt.encode("ascii").hex(),
            "digest_hex": hashlib.sha256(txt.encode("ascii")).hexdigest()})

    manifest_case("manifest-bridge", "the court box's bridge image: five LF-terminated lines", target, version, len(image), image_sha)
    manifest_case("manifest-gate", "the door gate's image", "door_gate", "2.0.1", len(gate_image), gate_sha)
    manifest_case("manifest-widest", "the widest legal fields: three-digit version parts and the largest door image",
                  "door_gate", "999.999.999", TARGET_MAX_BYTES["door_gate"], "f" * 64)

    def sig_case(cid, note, fields, signature, key="public_key", valid=True, reason="ok"):
        txt = manifest_text(fields["target"], fields["version"], fields["size"], fields["sha256"])
        n = N if key == "public_key" else N_OTHER
        got = verify(txt, signature, n)
        assert got == (valid, reason), (cid, got)
        cases["signatures"].append({"id": cid, "note": note, "fields": fields, "sig": signature,
                                    "key": key, "valid": valid, "reason": reason})

    base = {"target": target, "version": version, "size": len(image), "sha256": image_sha}
    sig_case("sig-valid", "the signature the founder's tool would produce, under the test key", base, sig)
    sig_case("sig-valid-gate", "the gate image's signature", dict(target="door_gate", version="2.0.1",
             size=len(gate_image), sha256=gate_sha), gate_offer["sig"])
    sig_case("sig-version-tampered", "the same signature claimed for a newer version: the version is inside the signed text",
             dict(base, version="3.0.2"), sig, valid=False, reason="sig")
    sig_case("sig-target-tampered", "a bridge signature offered to a door: the target is inside the signed text",
             dict(base, target="door_gate"), sig, valid=False, reason="sig")
    sig_case("sig-size-tampered", "one byte longer", dict(base, size=len(image) + 1), sig, valid=False, reason="sig")
    sig_case("sig-digest-tampered", "an image whose hash differs in one nibble",
             dict(base, sha256=image_sha[:-1] + ("0" if image_sha[-1] != "0" else "1")), sig, valid=False, reason="sig")
    sig_case("sig-other-key", "a valid signature by a DIFFERENT key — what a rogue server on the LAN could produce",
             base, sign(manifest_text(**base), N_OTHER, D_OTHER), valid=False, reason="sig")
    sig_case("sig-under-other-key-verifies-there", "the same rogue signature checked against the key that made it: proves the vector above fails for the key, not the encoding",
             base, sign(manifest_text(**base), N_OTHER, D_OTHER), key="other_public_key")
    sig_case("sig-truncated", "one character short", base, sig[:-1], valid=False, reason="sig_encoding")
    sig_case("sig-padded", "standard base64 padding is not this encoding", base, sig[:-2] + "==", valid=False, reason="sig_encoding")
    sig_case("sig-not-base64url", "a '+' from the other base64 alphabet", base, "+" + sig[1:], valid=False, reason="sig_encoding")
    over = b64url((N + 1).to_bytes(SIG_BYTES, "big"))
    sig_case("sig-out-of-range", "a signature integer >= the modulus is refused before exponentiation", base, over,
             valid=False, reason="sig_range")
    zero = b64url(bytes(SIG_BYTES))
    sig_case("sig-zero", "all-zero block", base, zero, valid=False, reason="sig")

    def version_case(cid, note, running, offered, failed, accept, reason):
        assert accept_version(running, offered, failed) == (accept, reason), cid
        cases["versions"].append({"id": cid, "note": note, "running": running, "offered": offered,
                                  "failed": failed, "accept": accept, "reason": reason})

    version_case("ver-patch-newer", "", "3.0.0", "3.0.1", [], True, "ok")
    version_case("ver-numeric-not-lexical", "10 > 9: compared as numbers, never as text", "3.0.9", "3.0.10", [], True, "ok")
    version_case("ver-minor-beats-patch", "", "3.0.99", "3.1.0", [], True, "ok")
    version_case("ver-major", "", "2.3.0", "3.0.0", [], True, "ok")
    version_case("ver-equal", "the running version is never re-flashed", "3.0.1", "3.0.1", [], False, "not_newer")
    version_case("ver-older", "a replayed older signed image is refused here, before any byte is downloaded",
                 "3.0.1", "3.0.0", [], False, "not_newer")
    version_case("ver-failed-before", "a version this board rolled back from is never taken again, whatever the server says",
                 "3.0.1", "3.0.2", ["3.0.2"], False, "failed_before")
    version_case("ver-failed-other", "a failed version does not block a different, newer one", "3.0.1", "3.0.3", ["3.0.2"], True, "ok")
    version_case("ver-leading-zero", "", "3.0.1", "3.0.02", [], False, "version_format")
    version_case("ver-prefix-v", "", "3.0.1", "v3.0.2", [], False, "version_format")
    version_case("ver-two-parts", "", "3.0.1", "3.1", [], False, "version_format")
    version_case("ver-suffix", "no pre-release tags: an image is a release or it is not offered", "3.0.1", "3.0.2-rc1", [], False, "version_format")
    version_case("ver-four-digit-part", "", "3.0.1", "3.0.1000", [], False, "version_format")

    def offer_case(cid, note, ota, own, accept, reason):
        assert parse_offer(ota, own) == (accept, reason), (cid, parse_offer(ota, own))
        cases["offers"].append({"id": cid, "note": note, "own_target": own, "ota": ota,
                                "accept": accept, "reason": reason})

    offer_case("offer-valid-bridge", "", offer, "court_bridge", True, "ok")
    offer_case("offer-valid-gate", "", gate_offer, "door_gate", True, "ok")
    offer_case("offer-extra-field-ignored", "an additive field a later server sends", dict(offer, rollout="all"), "court_bridge", True, "ok")
    offer_case("offer-other-target", "a door image offered to a court box", gate_offer, "court_bridge", False, "target_mismatch")
    offer_case("offer-unknown-target", "", dict(offer, target="court_mega"), "court_bridge", False, "target_unknown")
    offer_case("offer-missing-sig", "", {k: v for k, v in offer.items() if k != "sig"}, "court_bridge", False, "missing_sig")
    offer_case("offer-size-zero", "", dict(offer, size=0), "court_bridge", False, "size")
    offer_case("offer-size-over-slot", "larger than the target can stage", dict(offer, size=TARGET_MAX_BYTES["court_bridge"] + 1),
               "court_bridge", False, "size")
    offer_case("offer-size-string", "a number, never a string", dict(offer, size=str(len(image))), "court_bridge", False, "size")
    offer_case("offer-sha-uppercase", "lowercase hex only", dict(offer, sha256=image_sha.upper()), "court_bridge", False, "sha256_format")
    offer_case("offer-absolute-url", "the box pulls ONLY from its configured server: an absolute URL is refused",
               dict(offer, path="http://192.168.1.66/fw.bin"), "court_bridge", False, "path")
    offer_case("offer-path-traversal", "", dict(offer, path=PATH_PREFIX + "../admin"), "court_bridge", False, "path")
    offer_case("offer-path-query", "", dict(offer, path=PATH_PREFIX + "r1?x=1"), "court_bridge", False, "path")
    offer_case("offer-path-other-prefix", "", dict(offer, path="/api/v1/admin/firmware/r1"), "court_bridge", False, "path")
    offer_case("offer-version-format", "", dict(offer, version="3.0"), "court_bridge", False, "version_format")

    cases["images"].append({
        "id": "image-bridge", "note": "stream these bytes in any chunking: SHA-256 must equal the offer's sha256 and the "
        "byte count its size, and only then is the signature over the manifest checked and the image committed",
        "image_hex": image.hex(), "size": len(image), "sha256": image_sha, "offer": offer})
    cases["images"].append({
        "id": "image-gate", "note": "the door gate's", "image_hex": gate_image.hex(), "size": len(gate_image),
        "sha256": gate_sha, "offer": gate_offer})

    (HERE / "cases.json").write_text(json.dumps(cases, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    manifest = {
        "description": "Signed OTA for the ESP8266 bridge and the ESP32 door gate: manifest text, signature, version gate, offer grammar, image hashing.",
        "authority": "docs/specs/device-api.md section 7; gen_cases.py beside this file is the reference implementation.",
        "generator": "src/contracts/device-protocol/ota/gen_cases.py",
        "read_by": ["fw-shared", "csharp"],
        "case_count": {k: len(v) for k, v in cases.items() if isinstance(v, list)},
    }
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
